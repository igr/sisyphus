/** The seven sisters, spread wide; the faintest, Merope, has no rays. */
private val PLEIADES_ICON = Pixels(16, 16).apply {
    val bright = rgb(0xFFFFFF)
    val dim = rgb(0x9098C0)
    PLEIADES.forEachIndexed { k, (dx, dy) ->
        val x = 2 + dx * 3 / 2
        val y = 3 + (dy + 1) * 3 / 2
        if (k == PLEIADES.size - 1) {
            this[x, y] = dim
        } else {
            this[x, y] = bright
            for ((ox, oy) in listOf(-1 to 0, 1 to 0, 0 to -1, 0 to 1)) this[x + ox, y + oy] = dim
        }
    }
}

